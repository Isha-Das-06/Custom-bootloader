#!/usr/bin/env python3
"""
imgtool -- key management, image signing and flash-image assembly.

  keygen   <key.pem> [--header pubkey.h]    new Ed25519 signing key (+ C header for the bootloader)
  pubhdr   <key.pem> <pubkey.h>             (re)generate the bootloader's public-key header
  sign     --key K --version X.Y.Z in.bin out.img
  info     <image.img> [--key K]            dump + verify a signed image
  mkflash0 <bootloader.bin> <flash0.bin>    64 MiB pflash0 image (bootloader at 0)
  mkflash1 <flash1.bin> [--slot-a img] [--slot-b img]   64 MiB pflash1 (metadata erased)

Image header layout must match common/image.h.
"""
import argparse
import hashlib
import struct
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey, Ed25519PublicKey)
from cryptography.exceptions import InvalidSignature

IMAGE_MAGIC = 0x4D494F41
HEADER_SIZE = 256
SIGNED_BYTES = 192
LOAD_ADDR = 0x40100000

FLASH_BANK_SIZE = 64 * 1024 * 1024
SLOT_A_OFF = 0x100000
SLOT_B_OFF = 0x200000
SLOT_SIZE = 0x100000

HDR_FMT = "<8I64s8s88s"   # fields up to the signature (192 bytes)
assert struct.calcsize(HDR_FMT) == SIGNED_BYTES


def parse_version(s):
    parts = [int(x) for x in s.split(".")]
    if len(parts) != 3 or any(not 0 <= p <= 255 for p in parts):
        raise argparse.ArgumentTypeError("version must be X.Y.Z with 0..255 each")
    return (parts[0] << 16) | (parts[1] << 8) | parts[2]


def fmt_version(v):
    return f"{(v >> 16) & 0xff}.{(v >> 8) & 0xff}.{v & 0xff}"


def load_key(path):
    with open(path, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)


def raw_pub(pub: Ed25519PublicKey) -> bytes:
    return pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def key_id(pub_raw: bytes) -> bytes:
    return hashlib.sha512(pub_raw).digest()[:8]


def write_pubkey_header(key, path):
    pub = raw_pub(key.public_key())
    kid = key_id(pub)
    arr = lambda b: ", ".join(f"0x{x:02x}" for x in b)
    with open(path, "w") as f:
        f.write("/* generated by tools/imgtool.py -- the bootloader's root of trust */\n")
        f.write("#ifndef PUBKEY_H\n#define PUBKEY_H\n#include <stdint.h>\n")
        f.write(f"static const uint8_t signing_pubkey[32] = {{ {arr(pub)} }};\n")
        f.write(f"static const uint8_t signing_key_id[8] = {{ {arr(kid)} }};\n")
        f.write("#endif\n")


def cmd_keygen(a):
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(serialization.Encoding.PEM,
                            serialization.PrivateFormat.PKCS8,
                            serialization.NoEncryption())
    with open(a.key, "wb") as f:
        f.write(pem)
    if a.header:
        write_pubkey_header(key, a.header)
    print(f"generated {a.key} (key id {key_id(raw_pub(key.public_key())).hex()})")


def cmd_pubhdr(a):
    write_pubkey_header(load_key(a.key), a.header)


def build_image(payload, key, version, load=LOAD_ADDR, entry=None, flags=0):
    entry = load if entry is None else entry
    digest = hashlib.sha512(payload).digest()
    kid = key_id(raw_pub(key.public_key()))
    signed = struct.pack(HDR_FMT, IMAGE_MAGIC, HEADER_SIZE, len(payload), load, entry,
                         version, flags, 0, digest, kid, b"\0" * 56)
    sig = key.sign(signed)
    return signed + sig + payload


def cmd_sign(a):
    with open(a.input, "rb") as f:
        payload = f.read()
    img = build_image(payload, load_key(a.key), a.version)
    if len(img) > SLOT_SIZE:
        sys.exit(f"image too large for a slot: {len(img)} > {SLOT_SIZE}")
    with open(a.output, "wb") as f:
        f.write(img)
    print(f"signed {a.output}: v{fmt_version(a.version)}, {len(payload)} byte payload")


def cmd_info(a):
    with open(a.image, "rb") as f:
        img = f.read()
    fields = struct.unpack(HDR_FMT, img[:SIGNED_BYTES])
    magic, hsz, size, load, entry, ver, flags, _, digest, kid, _ = fields
    sig = img[SIGNED_BYTES:HEADER_SIZE]
    payload = img[HEADER_SIZE:HEADER_SIZE + size]
    print(f"magic      0x{magic:08x} {'ok' if magic == IMAGE_MAGIC else 'BAD'}")
    print(f"version    {fmt_version(ver)}")
    print(f"size       {size}")
    print(f"load/entry 0x{load:08x} / 0x{entry:08x}")
    print(f"key id     {kid.hex()}")
    print(f"sha512     {'ok' if hashlib.sha512(payload).digest() == digest else 'MISMATCH'}")
    if a.key:
        pub = load_key(a.key).public_key()
        try:
            pub.verify(sig, img[:SIGNED_BYTES])
            print("signature  ok")
        except InvalidSignature:
            print("signature  INVALID")


def cmd_mkflash0(a):
    with open(a.bootloader, "rb") as f:
        bl = f.read()
    if len(bl) > SLOT_A_OFF:
        sys.exit("bootloader too large")
    with open(a.output, "wb") as f:
        f.write(bl + b"\xff" * (FLASH_BANK_SIZE - len(bl)))


def cmd_mkflash1(a):
    flash = bytearray(b"\xff" * FLASH_BANK_SIZE)
    for off, path in ((SLOT_A_OFF, a.slot_a), (SLOT_B_OFF, a.slot_b)):
        if path:
            with open(path, "rb") as f:
                data = f.read()
            assert len(data) <= SLOT_SIZE
            flash[off:off + len(data)] = data
    with open(a.output, "wb") as f:
        f.write(flash)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest="cmd", required=True)

    s = sp.add_parser("keygen"); s.add_argument("key"); s.add_argument("--header")
    s.set_defaults(fn=cmd_keygen)
    s = sp.add_parser("pubhdr"); s.add_argument("key"); s.add_argument("header")
    s.set_defaults(fn=cmd_pubhdr)
    s = sp.add_parser("sign"); s.add_argument("--key", required=True)
    s.add_argument("--version", required=True, type=parse_version)
    s.add_argument("input"); s.add_argument("output"); s.set_defaults(fn=cmd_sign)
    s = sp.add_parser("info"); s.add_argument("image"); s.add_argument("--key")
    s.set_defaults(fn=cmd_info)
    s = sp.add_parser("mkflash0"); s.add_argument("bootloader"); s.add_argument("output")
    s.set_defaults(fn=cmd_mkflash0)
    s = sp.add_parser("mkflash1"); s.add_argument("output")
    s.add_argument("--slot-a"); s.add_argument("--slot-b"); s.set_defaults(fn=cmd_mkflash1)

    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
